#pragma once

#include <algorithm>
#include <cmath>

#include "yeet_control/pi_controller.hpp"

namespace sfc {

/**
 * @brief Implements the inner current control loop for an LCI drive.
 *
 * This class encapsulates the full functionality of a high-performance current
 * controller as described in the design documentation. It is suitable for both
 * high-performance LCI drives and soft-starter applications.
 *
 * The controller architecture includes:
 * 1.  Current Reference Limiting: Enforces safe operational bounds on the torque command.
 * 2.  PI Controller: Processes the current error to generate a corrective voltage.
 * 3.  Feedforward Compensation: Proactively cancels the inverter back-EMF disturbance.
 * 4.  Linearization: Uses an arccos function to convert the desired DC voltage into
 *     a rectifier firing angle, linearizing the plant response.
 *
 * @tparam T The floating-point type for calculations (e.g., float, double).
 */
template <typename T>
class sfc_current_controller {
    static_assert(std::is_floating_point_v<T>, "sfc_current_controller requires a floating-point type");

public:
    /**
     * @brief Configuration parameters for the current controller.
     */
    struct Config {
        T kp;                             // Proportional gain for the PI controller (dimensionless).
        T ki;                             // Integral gain for the PI controller (dimensionless).
        T ts;                             // Sampling time (seconds).
        T dc_link_current_min_pu;         // Minimum limit for the DC link current reference (pu).
        T dc_link_current_max_pu;         // Maximum limit for the DC link current reference (pu).
        T grid_firing_angle_min_radians;  // Minimum firing angle limit (rad).
        T grid_firing_angle_max_radians;  // Maximum firing angle limit (rad).
    };

    /**
     * @brief Real-time inputs required for the controller update.
     */
    struct Inputs {
        T dc_link_current_ref_pu;                 // Per-unit current reference from the outer loop.
        T dc_link_current_measured_pu;            // Measured per-unit DC link current.
        T grid_voltage_line_rms_measured_pu;      // Measured per-unit source RMS line-to-line voltage.
        T dc_link_voltage_inverter_estimated_pu;  // Estimated per-unit inverter back-EMF for feedforward.
    };

    /**
     * @brief Outputs generated by the controller.
     */
    struct Outputs {
        T grid_firing_angle_ref_radians;   // Final firing angle reference for the rectifier (rad).
        T dc_link_current_ref_limited_pu;  // The limited per-unit current reference used by the controller.
    };

    /**
     * @brief Configures the LCI current controller.
     *
     * @param config The configuration parameters.
     */
    void configure(const Config& config) {
        _pi_controller.configure(config.kp, config.ki, config.ts);
        // The PI output is a per-unit voltage. A reasonable limit for the DC voltage is ~1.5 pu.
        _pi_controller.set_output_limits(-1.5, 1.5);
        _pi_controller.enable_integrator_clamping(true);

        _dc_link_current_min_pu = config.dc_link_current_min_pu;
        _dc_link_current_max_pu = config.dc_link_current_max_pu;
        _grid_firing_angle_min_radians = config.grid_firing_angle_min_radians;
        _grid_firing_angle_max_radians = config.grid_firing_angle_max_radians;
    }

    /**
     * @brief Executes one update cycle of the current controller.
     *
     * @param inputs The real-time inputs for the controller.
     * @return The calculated outputs, including the firing angle.
     */
    Outputs update(const Inputs& inputs) {
        // Step 1: Limit the incoming current reference
        const T dc_link_current_ref_limited_pu =
            std::clamp(inputs.dc_link_current_ref_pu, _dc_link_current_min_pu, _dc_link_current_max_pu);

        // Step 2: Calculate the error signal
        const T current_error_pu = dc_link_current_ref_limited_pu - inputs.dc_link_current_measured_pu;

        // Step 3: Update the PI controller
        const T pi_output_voltage_pu = _pi_controller.update(current_error_pu);

        // Step 4: Add feedforward compensation
        const T total_control_voltage_pu = pi_output_voltage_pu + inputs.dc_link_voltage_inverter_estimated_pu;

        // Step 5: Linearize using arccos and calculate the firing angle
        // In per-unit, V_dr_pu = V_ll_s_pu * cos(alpha).
        // So, cos(alpha) = V_dr_pu / V_ll_s_pu.
        T cos_alpha = 0.0;
        if (std::abs(inputs.grid_voltage_line_rms_measured_pu) > 1e-9) {  // Avoid division by zero
            cos_alpha = total_control_voltage_pu / inputs.grid_voltage_line_rms_measured_pu;
        }

        // Step 6: Clamp the result and compute the final angle
        const T cos_alpha_clamped = std::clamp(cos_alpha, static_cast<T>(-1.0), static_cast<T>(1.0));
        const T grid_firing_angle_ref_unclamped_radians = std::acos(cos_alpha_clamped);

        // Clamp the final firing angle to the configured limits
        const T grid_firing_angle_ref_radians = std::clamp(
            grid_firing_angle_ref_unclamped_radians, _grid_firing_angle_min_radians, _grid_firing_angle_max_radians);

        return Outputs{grid_firing_angle_ref_radians, dc_link_current_ref_limited_pu};
    }

private:
    yeet::control::pi_controller<T> _pi_controller;

    T _dc_link_current_min_pu{};
    T _dc_link_current_max_pu{};
    T _grid_firing_angle_min_radians{};
    T _grid_firing_angle_max_radians{};
};

}  // namespace sfc
