#ifndef SFC_SPEED_CONTROLLER_HPP
#define SFC_SPEED_CONTROLLER_HPP

#include <cmath>
#include <type_traits>

#include "yeet_control/pi_controller.hpp"

namespace sfc {

/**
 * @brief Implements the outer speed control loop for an LCI drive.
 *
 * This class encapsulates the functionality of a speed controller suitable for
 * LCI soft-starter and drive applications. It acts as the master controller in a
 * cascaded control scheme, providing the current reference to the inner current loop.
 *
 * The controller architecture includes:
 * 1.  PI Controller: Processes the speed error to generate a torque-producing current reference.
 * 2.  Anti-windup: The output is clamped, and the PI controller's internal integrator
 *     clamping is used to prevent wind-up when the current command saturates.
 *
 * @tparam T The floating-point type for calculations (e.g., float, double).
 */
template <typename T>
class sfc_speed_controller {
    static_assert(std::is_floating_point_v<T>, "sfc_speed_controller requires a floating-point type");

public:
    /**
     * @brief Configuration parameters for the speed controller.
     */
    struct Config {
        T kp;                          // Proportional gain for the PI controller (dimensionless).
        T ki;                          // Integral gain for the PI controller (dimensionless).
        T ts;                          // Sampling time (seconds).
        T dc_link_current_ref_min_pu;  // Minimum limit for the output current reference (pu).
        T dc_link_current_ref_max_pu;  // Maximum limit for the output current reference (pu).
    };

    /**
     * @brief Real-time inputs required for the controller update.
     */
    struct Inputs {
        T speed_ref_pu;       // The desired speed reference in per-unit.
        T speed_measured_pu;  // The measured motor speed in per-unit.
    };

    /**
     * @brief Outputs generated by the controller.
     */
    struct Outputs {
        T dc_link_current_ref_pu;  // The calculated DC link current reference in per-unit.
    };

    /**
     * @brief Configures the LCI speed controller.
     *
     * @param config The configuration parameters.
     */
    void configure(const Config& config) {
        _pi_controller.configure(config.kp, config.ki, config.ts);
        _pi_controller.set_output_limits(config.dc_link_current_ref_min_pu, config.dc_link_current_ref_max_pu);
        _pi_controller.enable_integrator_clamping(true);
    }

    /**
     * @brief Executes one update cycle of the speed controller.
     *
     * @param inputs The real-time inputs for the controller.
     * @return The calculated outputs, including the DC link current reference.
     */
    Outputs update(const Inputs& inputs) {
        // Step 1: Calculate the speed error in per-unit
        const T speed_error_pu = inputs.speed_ref_pu - inputs.speed_measured_pu;

        // Step 2: Update the PI controller to get the DC link current reference
        const T dc_link_current_ref_pu = _pi_controller.update(speed_error_pu);

        return {dc_link_current_ref_pu};
    }

    /**
     * @brief Resets the internal state of the controller.
     */
    void reset() { _pi_controller.reset(); }

private:
    yeet::control::pi_controller<T> _pi_controller;
};

}  // namespace sfc

#endif  // SFC_SPEED_CONTROLLER_HPP
