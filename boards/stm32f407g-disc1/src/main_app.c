/**
 * @file main_app.c
 * @brief Yeet embedded application entry point for STM32F407G-DISC1
 */

#include "main.h"
#include "usb_host.h"

/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void)
{
    /* MCU Configuration--------------------------------------------------------*/

    /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
    HAL_Init();

    /* Configure the system clock */
    SystemClock_Config();

    /* Initialize all configured peripherals */
    MX_GPIO_Init();
    MX_I2C1_Init();
    MX_I2S3_Init();
    MX_SPI1_Init();
    MX_USB_HOST_Init();

    /* Infinite loop */
    while (1) {
        MX_USB_HOST_Process();

        /* Your yeet control algorithms can go here */

        /* Toggle LED or do something to show it's running */
        HAL_Delay(100);
    }
}

